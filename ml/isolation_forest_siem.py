import argparse
import json
import os
import re
from datetime import datetime, timedelta

import numpy as np
import pandas as pd
import matplotlib
matplotlib.use("Agg")  # write figures to disk rather than open a window
import matplotlib.pyplot as plt
from sklearn.ensemble import IsolationForest
from sklearn.preprocessing import StandardScaler
import joblib

# Fixed random seed so model results are reproducible across runs. Common
# convention in the ML literature; any integer would do.
RANDOM_STATE = 42
OUTDIR = "docs/phase2_ml_siem"

# IP address of my Kali attacker VM during the Phase 1 attack run.
# Used only to evaluate detection accuracy after scoring - never given
# to the model as an input feature, so detection has to be based on
# behaviour alone.
ATTACKER_IP = "192.168.56.103"

# The four Windows Security event IDs that carry the most authentication
# signal in this lab. Each maps to a known type of activity.
EID_FAILED = 4625      # An account failed to log on
EID_SUCCESS = 4624     # An account was successfully logged on
EID_LOCKOUT = 4740     # A user account was locked out
EID_PRIV = 4672        # Special privileges assigned to new logon

# Event 4703 ("token right adjusted") is generated by Fluent Bit's own
# service process every few seconds while it ships logs. In this lab it
# accounted for ~94% of all recorded events (8,155 of 8,636) and carries
# no source IP, so it is excluded as shipper noise. Other low-volume
# Windows audit events were retained even when small, because events
# such as 4688 (process creation) can carry legitimate security signal.
NOISE_EVENT_IDS = {4703}


# =============================================================================
# 1. DATA LOADING
# =============================================================================

def load_opensearch_export(path):
    """Read an OpenSearch JSON export and return a clean table of events.

    OpenSearch exports come in a few different shapes (a wrapped response,
    a flat list, or one JSON per line). This function handles all three so
    the same code works regardless of how the export was produced.

    For each event it extracts five fields the model later needs:
    timestamp, event_id, src_ip, user, logon_type. Because winlogbeat in
    this lab did not promote fields like IpAddress to top-level JSON keys,
    the function falls back to parsing them out of the Message text when
    they are not available directly.
    """
    rows = []
    with open(path, "r", encoding="utf-8") as fh:
        text = fh.read().strip()

    # Detect the shape of the export and produce a flat list of event docs.
    docs = []
    try:
        obj = json.loads(text)
        if isinstance(obj, dict) and "hits" in obj:
            docs = [h.get("_source", h) for h in obj["hits"]["hits"]]
        elif isinstance(obj, list):
            docs = obj
        else:
            docs = [obj]
    except json.JSONDecodeError:
        # Fall back to newline-delimited JSON
        for line in text.splitlines():
            line = line.strip()
            if not line:
                continue
            d = json.loads(line)
            docs.append(d.get("_source", d))

    for d in docs:
        # Extract source IP, account name and logon type. Each falls back
        # to parsing the Message text when the field is not promoted.
        msg = d.get("Message", "") or ""

        ip = _first(d, ["src_ip", "source_ip", "IpAddress",
                        "winlog.event_data.IpAddress", "SourceIp"])
        if not ip:
            ip = _parse_msg(msg, ["Source Network Address", "Network Address",
                                  "Client Address"])

        user = _first(d, ["user", "TargetUserName", "AccountName",
                          "winlog.event_data.TargetUserName"])
        if not user:
            user = _parse_msg(msg, ["Account Name"])

        ltype = _to_int(_first(d, ["logon_type", "LogonType",
                                   "winlog.event_data.LogonType"]))
        if ltype is None:
            ltype = _to_int(_parse_msg(msg, ["Logon Type"]))

        rows.append({
            "timestamp": _first(d, ["@timestamp", "timestamp", "TimeCreated",
                                    "EventTime"]),
            "event_id": _to_int(_first(d, ["event_id", "EventID",
                                           "winlog.event_id", "EventCode"])),
            "src_ip": ip,
            "user": user,
            "logon_type": ltype,
        })

    df = pd.DataFrame(rows)
    df["timestamp"] = pd.to_datetime(df["timestamp"], errors="coerce", utc=True)
    df = df.dropna(subset=["timestamp"])
    return df


def _first(d, keys):
    """Look through a list of possible field names and return whichever
    one is actually present in the data. Different log shippers store
    the same information under different keys, so trying several names
    makes the loader portable. Dotted keys like 'winlog.event_data.IpAddress'
    are followed into nested sub-dictionaries.
    """
    for k in keys:
        if k in d and d[k] not in (None, ""):
            return d[k]
        if "." in k:  # nested-path lookup
            cur, ok = d, True
            for part in k.split("."):
                if isinstance(cur, dict) and part in cur:
                    cur = cur[part]
                else:
                    ok = False
                    break
            if ok and cur not in (None, ""):
                return cur
    return None


def _parse_msg(msg, labels):
    """Extract a field value from the Windows event Message text.

    In this lab the OpenSearch index stored each event's Message as a
    single string, with key information like the source IP and username
    embedded inside it rather than promoted to JSON fields. This helper
    runs a regex over the Message text to pull out the value on the same
    line as a given label. Empty placeholders ('-') are skipped.
    """
    for label in labels:
        m = re.search(rf"{re.escape(label)}\s*:\s*([^\r\n]+)", msg)
        if m:
            val = m.group(1).strip()
            if val and val != "-":
                return val
    return None


def _to_int(v):
    """Safely cast a value to int. Returns None for missing or non-numeric
    inputs rather than raising, so the rest of the pipeline can carry on."""
    try:
        return int(v)
    except (TypeError, ValueError):
        return None


