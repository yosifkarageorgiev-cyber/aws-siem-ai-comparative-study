def _plot_scores(feats):
    """Histogram showing how the model's anomaly scores are distributed
    across benign and attacker windows. A well-performing model should
    show the two populations clearly separated, with attacker windows
    sitting at higher scores than benign windows. Heavy overlap would
    indicate the model is not distinguishing the two effectively.
    """
    fig, ax = plt.subplots(figsize=(9, 5))

    # Pick the right ground-truth mask: labelled attacks if present,
    # otherwise attacker IP for the real-data run.
    if (feats["_attack"] != "benign").any():
        attack_mask = feats["_attack"] != "benign"
    else:
        attack_mask = feats["src_ip"] == ATTACKER_IP

    benign = feats[~attack_mask]["anomaly_score"]
    attack = feats[attack_mask]["anomaly_score"]
    ax.hist(benign, bins=40, alpha=0.7, label="Benign windows")
    ax.hist(attack, bins=40, alpha=0.9, label="Attacker windows")
    ax.set_xlabel("Anomaly score (higher = more anomalous)")
    ax.set_ylabel("Number of windows")
    ax.set_title("Isolation Forest anomaly score distribution")
    ax.legend()
    fig.tight_layout()
    fig.savefig(os.path.join(OUTDIR, "fig_anomaly_scores.png"), dpi=150)
    plt.close(fig)


def _plot_comparison(detected, all_attacks, ml_rate, synthetic_mode):
    """Side-by-side bar chart of Phase 1 (rule-based) vs Phase 2 (ML)
    detection rate. The Phase 1 figure of 57% is fixed from the Phase 1
    results section; the Phase 2 figure is computed live from the current
    model run.
    """
    fig, ax = plt.subplots(figsize=(7, 5))
    phase1 = 4 / 7 * 100
    if synthetic_mode:
        phase2 = (len(detected) / len(all_attacks) * 100) if all_attacks else 0.0
    else:
        phase2 = ml_rate
    bars = ax.bar(["Phase 1\n(traditional SIEM)", "Phase 2\n(ML-enhanced)"],
                  [phase1, phase2], color=["#888888", "#2a7de1"])
    ax.set_ylabel("Detection rate (%)")
    ax.set_ylim(0, 110)
    ax.set_title("Detection rate: traditional vs ML-enhanced SIEM")
    for b, v in zip(bars, [phase1, phase2]):
        ypos = v - 6 if v > 95 else v + 2
        color = "white" if v > 95 else "black"
        ax.text(b.get_x() + b.get_width() / 2, ypos, f"{v:.0f}%",
                ha="center", color=color, fontweight="bold")
    fig.tight_layout()
    fig.savefig(os.path.join(OUTDIR, "fig_detection_comparison.png"), dpi=150)
    plt.close(fig)


