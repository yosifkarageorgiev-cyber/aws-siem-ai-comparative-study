def main():
    ap = argparse.ArgumentParser(description="Phase 2 Isolation Forest SIEM model")
    ap.add_argument("--input", help="OpenSearch export (JSON/NDJSON). "
                                    "Omit to use built-in synthetic data.")
    args = ap.parse_args()

    if args.input:
        print(f"[*] Loading real data from {args.input}")
        df = load_opensearch_export(args.input)
    else:
        print("[*] No --input given; generating synthetic Phase 1-matched data.")
        df = make_synthetic()
    run(df)


if __name__ == "__main__":
    main()
